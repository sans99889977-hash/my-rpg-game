-- RPG Adventure: account profiles + global world chat
-- Run after supabase_setup.sql in Supabase SQL Editor.

create table if not exists public.world_chat (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null check (char_length(username) between 1 and 24),
  message text not null check (char_length(message) between 1 and 240),
  created_at timestamptz not null default now()
);

create index if not exists world_chat_created_at_idx
  on public.world_chat (created_at desc);

alter table public.world_chat enable row level security;

drop policy if exists "world chat readable by signed in users" on public.world_chat;
create policy "world chat readable by signed in users"
  on public.world_chat for select to authenticated using (true);

drop policy if exists "players send own world chat" on public.world_chat;
create policy "players send own world chat"
  on public.world_chat for insert to authenticated
  with check (user_id = auth.uid());

-- Optional account-management flag. Set the trusted administrator manually
-- AFTER the Mask account has been created and its email verified.
alter table public.profiles
  add column if not exists is_admin boolean not null default false;

-- Admin directory function returns names only; it NEVER returns passwords,
-- password hashes, auth tokens, or private save data.
create or replace function public.admin_player_directory()
returns table (id uuid, username text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.is_admin = true
  ) then
    raise exception 'admin only';
  end if;
  return query
    select p.id, p.username, p.created_at
    from public.profiles p
    order by p.created_at desc;
end;
$$;
revoke all on function public.admin_player_directory() from public;
grant execute on function public.admin_player_directory() to authenticated;

-- Enable database change feed for the world chat (safe to run more than once).
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public' and tablename = 'world_chat'
  ) then
    alter publication supabase_realtime add table public.world_chat;
  end if;
end $$;

